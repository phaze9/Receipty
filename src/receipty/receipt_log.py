"""Action logging for the Receipty server.

Actions performed in the Receipty server — browser UI, REST API, or MCP tools —
are logged to LOG.md in the workspace root. Each entry's message is generated
by an LLM via a model-connect library of the deployment's choice.

Logging is asynchronous: log_action() enqueues the job and returns immediately;
a single background worker thread processes jobs one at a time (strictly
sequential, one receipt at a time) and writes LOG.md. Status updates are
printed to stdout.

Pending jobs are persisted to `.receipty/pending-log.json` before enqueueing,
so a server restart does not lose entries: on startup the pending file is
replayed and each queued entry is written. A job is removed from the file
once its entry has been written; a job whose write fails is kept for the next
startup.

Configuration (env vars; logging is off by default — set RECEIPTY_LOG to
1/true/on/yes to enable; logging is skipped entirely when either of the two
required values is unset):
  RECEIPTY_LOG           Enable logging (default off).
  RECEIPTY_LLM_URL       Chat-completions endpoint (required).
  RECEIPTY_MODEL_CONNECT Path to model_connect.py (required).
  MODEL_CONNECT_API_KEY  Bearer key (falls back to OMLX_API_KEY).
"""
from __future__ import annotations

import importlib.util
import json
import logging
import os
import queue
import re
import threading
import time
import uuid
from datetime import datetime
from pathlib import Path

logger = logging.getLogger(__name__)

GENERATE_TIMEOUT = 300.0
MAX_DETAIL_CHARS = 200

SECRET_NAME_PATTERN = re.compile(
    r"(secret|password|passwd|token|credential|api[_-]?key|private[_-]?key|card|cvv|pin|ssn|auth)",
    re.IGNORECASE,
)


def is_secret_field(name) -> bool:
    return bool(SECRET_NAME_PATTERN.search(str(name)))


def format_fields(fields: dict | None, max_chars: int = MAX_DETAIL_CHARS) -> str:
    """Format non-secret field values for the log. Secret fields are redacted."""
    if not fields:
        return ""
    parts = []
    for key, value in fields.items():
        if is_secret_field(key):
            parts.append(f"{key}: [redacted]")
            continue
        if isinstance(value, str):
            rendered = value
        else:
            try:
                rendered = json.dumps(value, ensure_ascii=False, default=str)
            except Exception:
                rendered = str(value)
        rendered = rendered.strip().replace("\n", " ")
        parts.append(f'{key}: "{rendered}"')
    text = ", ".join(parts)
    if len(text) > max_chars:
        text = text[:max_chars] + "…"
    return text

LOG_HEADER = """# Action log

Log of actions performed in the Receipty server (browser UI, REST
API, or MCP tools). Newest entries appear first.

Rules:
- Entries are inserted at the top of the list whenever an action is performed.
- Each entry is one line: `YYYY-MM-DD HH:MM:SS — <message>` where the message is
  generated by the LLM via the model-connect library. Receipt-scoped actions
  append a deterministic ` — <link>` after the message.

## Entries

"""


def _split_log(text: str):
    """Split a LOG.md body into (header, [entry blocks]).

    The header is everything up to and including the '## Entries' marker;
    each remaining blank-line-separated block is one entry.
    """
    marker = "## Entries"
    idx = text.find(marker)
    if idx == -1:
        return LOG_HEADER, []
    header = text[: idx + len(marker)]
    body = text[idx + len(marker):]
    blocks = [b.strip() for b in re.split(r"\n\s*\n", body) if b.strip()]
    return header, blocks


def _log_path(workspace) -> Path:
    return workspace.root / "LOG.md"


def _enabled() -> bool:
    return os.environ.get("RECEIPTY_LOG", "").strip().lower() in ("1", "true", "on", "yes")


def _llm_url() -> str:
    return os.environ.get("RECEIPTY_LLM_URL", "").strip()


def _model_connect_path() -> Path | None:
    raw = os.environ.get("RECEIPTY_MODEL_CONNECT", "").strip()
    return Path(raw).expanduser() if raw else None


def _configured() -> bool:
    return bool(_llm_url()) and _model_connect_path() is not None


def _load_model_connect():
    path = _model_connect_path()
    if path is None:
        raise FileNotFoundError("RECEIPTY_MODEL_CONNECT is not set")
    if not path.exists():
        raise FileNotFoundError(f"model-connect not found: {path}")
    spec = importlib.util.spec_from_file_location("model_connect", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _api_key() -> str:
    return os.environ.get("MODEL_CONNECT_API_KEY") or os.environ.get("OMLX_API_KEY") or ""


def _truncate(detail: str) -> str:
    detail = detail.strip().replace("\n", " ")
    return detail[:MAX_DETAIL_CHARS]


def generate_message(action: str, detail: str, channel: str = "UI", timeout: float = GENERATE_TIMEOUT) -> str:
    """Generate a one-line message for a server action via the configured LLM."""
    mc = _load_model_connect()
    url = _llm_url()
    if not url:
        raise ValueError("RECEIPTY_LLM_URL is not set")
    model = mc.resolve_model(url)
    key = _api_key()
    previous = os.environ.get("MODEL_CONNECT_API_KEY")
    if key and not previous:
        os.environ["MODEL_CONNECT_API_KEY"] = key
    try:
        prompt = (
            "You log actions performed in the Receipty receipt workspace server. "
            "Write one short sentence (no quotes, no preamble) describing the action, "
            "including how it was performed. "
            f"Channel: {channel}\nAction type: {action}\nDetail: {_truncate(detail)}"
        )
        raw = mc.chat_completion(url, model, prompt, timeout)
        return mc.clean_content(raw)
    finally:
        if key and not previous:
            os.environ.pop("MODEL_CONNECT_API_KEY", None)


def _fallback_message(action: str, detail: str, channel: str) -> str:
    suffix = f" ({_truncate(detail)})" if detail.strip() else ""
    return f"{channel} action: {action}{suffix} (LLM unavailable)"


def _write_entry(workspace, timestamp: str, message: str, link: str | None) -> bool:
    path = _log_path(workspace)
    line = f"{timestamp} — {message}"
    if link:
        line += f" — {link}"
    try:
        if path.exists():
            header, entries = _split_log(path.read_text(encoding="utf-8"))
        else:
            header, entries = LOG_HEADER, []
        header = header.rstrip("\n") + "\n\n"
        blocks = [line] + entries
        path.write_text(header + "\n\n".join(blocks) + "\n", encoding="utf-8")
        return True
    except OSError:
        logger.exception("Could not write action log to %s", path)
        return False


# ---- Pending-job persistence ----------------------------------------------------

_PENDING_LOCK = threading.Lock()


def _pending_path(workspace) -> Path:
    return workspace.metadata / "pending-log.json"


def _load_pending(workspace) -> list:
    try:
        data = json.loads(_pending_path(workspace).read_text(encoding="utf-8"))
        if isinstance(data, list):
            return [j for j in data if isinstance(j, dict) and j.get("id")]
    except Exception:
        pass
    return []


def _save_pending(workspace, jobs: list) -> None:
    path = _pending_path(workspace)
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_name(path.name + ".tmp")
        tmp.write_text(json.dumps(jobs, ensure_ascii=False), encoding="utf-8")
        tmp.replace(path)
    except OSError:
        logger.exception("Could not write pending log queue to %s", path)


def _append_pending(workspace, job: dict) -> None:
    with _PENDING_LOCK:
        jobs = _load_pending(workspace)
        jobs.append(job)
        _save_pending(workspace, jobs)


def _remove_pending(workspace, job_id: str) -> None:
    with _PENDING_LOCK:
        jobs = _load_pending(workspace)
        kept = [j for j in jobs if j.get("id") != job_id]
        if len(kept) != len(jobs):
            _save_pending(workspace, kept)


# ---- Async worker ---------------------------------------------------------------

_QUEUE: queue.Queue = queue.Queue()
_STATE_LOCK = threading.Lock()
_IDLE = threading.Condition(_STATE_LOCK)
_PENDING = 0
_WORKER_STARTED = False


def _ensure_worker() -> None:
    global _WORKER_STARTED
    with _STATE_LOCK:
        if _WORKER_STARTED:
            return
        _WORKER_STARTED = True
    thread = threading.Thread(target=_worker_loop, daemon=True, name="receipt-log-worker")
    thread.start()


def _enqueue(workspace, job: dict) -> None:
    _ensure_worker()
    with _IDLE:
        global _PENDING
        _PENDING += 1
        _QUEUE.put((workspace, job))


def _worker_loop() -> None:
    while True:
        workspace, job = _QUEUE.get()
        try:
            _process(workspace, job)
        except Exception:
            logger.exception("Action log worker failed")
        finally:
            _QUEUE.task_done()
            with _IDLE:
                global _PENDING
                _PENDING -= 1
                if _PENDING == 0:
                    _IDLE.notify_all()


def _process(workspace, job: dict) -> None:
    action = job.get("action", "")
    detail = job.get("detail", "")
    channel = job.get("channel", "UI")
    link = job.get("link")
    timestamp = job.get("timestamp") or datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    print(f"[receipt-log] generating message: {action} ({channel})", flush=True)
    try:
        message = generate_message(action, detail, channel)
        if not message:
            raise ValueError("empty LLM message")
    except Exception as exc:
        logger.warning("Action log message generation failed: %s", exc)
        message = _fallback_message(action, detail, channel)
    print(f"[receipt-log] message: {message}", flush=True)
    ok = _write_entry(workspace, timestamp, message, link)
    if ok:
        print("[receipt-log] wrote entry to LOG.md", flush=True)
        _remove_pending(workspace, job["id"])
    else:
        print("[receipt-log] failed to write entry to LOG.md", flush=True)


def log_action(workspace, action: str, detail: str = "", channel: str = "UI", link: str | None = None) -> bool:
    """Enqueue one LOG.md entry (newest entry on top). Never raises; returns True when queued.

    `link` is a deterministic, caller-supplied reference appended to the line
    (e.g. a receipt URL); it is never generated by the LLM. The entry is
    generated and written by a background worker, one receipt at a time.
    """
    if not _enabled():
        return False
    if not _configured():
        return False
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    job = {
        "id": uuid.uuid4().hex,
        "action": action,
        "detail": detail,
        "channel": channel,
        "link": link,
        "timestamp": timestamp,
    }
    try:
        _append_pending(workspace, job)
    except Exception:
        logger.exception("Could not persist pending log job")
    _enqueue(workspace, job)
    print(f"[receipt-log] queued: {action} ({channel})", flush=True)
    return True


def replay_pending(workspace) -> int:
    """Enqueue any log jobs persisted before a restart (missing LOG.md entries).

    Returns the number of replayed jobs. Never raises; logging must not fail
    server startup.
    """
    if not _enabled():
        return 0
    if not _configured():
        return 0
    try:
        jobs = _load_pending(workspace)
    except Exception:
        logger.exception("Could not load pending log jobs")
        return 0
    if not jobs:
        return 0
    for job in jobs:
        _enqueue(workspace, job)
    print(f"[receipt-log] replayed {len(jobs)} pending entries", flush=True)
    return len(jobs)


def wait_for_idle(timeout: float = 10.0) -> bool:
    """Block until all queued log jobs are processed. Returns True on success."""
    deadline = time.time() + timeout
    with _IDLE:
        while _PENDING > 0:
            remaining = deadline - time.time()
            if remaining <= 0:
                return False
            _IDLE.wait(remaining)
        return True
